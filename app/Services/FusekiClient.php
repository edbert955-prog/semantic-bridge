<?php

namespace App\Services;

use Illuminate\Http\Client\PendingRequest;
use Illuminate\Support\Facades\Http;
use RuntimeException;
use Throwable;

/** HTTP client for Apache Jena Fuseki SPARQL Query, Update and Graph Store endpoints. */
class FusekiClient
{
    public function isConfigured(): bool
    {
        return (bool) config('semantic.fuseki.enabled')
            && filled(config('semantic.fuseki.query_url'))
            && filled(config('semantic.fuseki.update_url'))
            && filled(config('semantic.fuseki.data_url'));
    }

    public function health(): array
    {
        if (!$this->isConfigured()) {
            return [
                'configured' => false,
                'connected' => false,
                'status' => 'not_configured',
                'message' => 'Fuseki belum diaktifkan. RDF tetap dibuat sebagai file Turtle lokal.',
            ];
        }

        try {
            $result = $this->query('SELECT (COUNT(*) AS ?tripleCount) WHERE { GRAPH ?g { ?s ?p ?o } }');
            $count = $result['results']['bindings'][0]['tripleCount']['value'] ?? '0';

            return [
                'configured' => true,
                'connected' => true,
                'status' => 'ready',
                'triple_count' => (int) $count,
                'query_url' => config('semantic.fuseki.query_url'),
                'message' => 'Endpoint SPARQL Fuseki dapat diakses.',
            ];
        } catch (Throwable $e) {
            report($e);
            return [
                'configured' => true,
                'connected' => false,
                'status' => 'unavailable',
                'query_url' => config('semantic.fuseki.query_url'),
                'message' => 'Fuseki dikonfigurasi tetapi tidak merespons. Periksa server dan endpoint.',
            ];
        }
    }

    public function query(string $sparql): array
    {
        $this->requireConfigured();
        $response = $this->request()
            ->accept('application/sparql-results+json')
            ->withBody($sparql, 'application/sparql-query')
            ->post((string) config('semantic.fuseki.query_url'));

        if (!$response->successful()) {
            throw new RuntimeException('Fuseki query gagal dengan HTTP '.$response->status().'.');
        }

        $json = $response->json();
        if (!is_array($json)) {
            throw new RuntimeException('Fuseki tidak mengembalikan JSON SPARQL Results yang valid.');
        }

        return $json;
    }

    public function update(string $sparqlUpdate): void
    {
        $this->requireConfigured();
        $response = $this->request()
            ->withBody($sparqlUpdate, 'application/sparql-update')
            ->post((string) config('semantic.fuseki.update_url'));

        if (!$response->successful()) {
            throw new RuntimeException('Fuseki update gagal dengan HTTP '.$response->status().'.');
        }
    }

    public function publishTurtle(string $graphUri, string $turtle): array
    {
        $this->requireConfigured();
        if (!filter_var($graphUri, FILTER_VALIDATE_URL) || !in_array(parse_url($graphUri, PHP_URL_SCHEME), ['http', 'https'], true)) {
            throw new RuntimeException('Graph URI tidak valid.');
        }

        // Replace the named graph deterministically. The graph URI is generated by our app.
        $this->update('CLEAR SILENT GRAPH <'.$graphUri.'>');
        $url = rtrim((string) config('semantic.fuseki.data_url'), '?')
            .'?graph='.rawurlencode($graphUri);
        $response = $this->request()
            ->withBody($turtle, 'text/turtle; charset=UTF-8')
            ->post($url);

        if (!$response->successful()) {
            throw new RuntimeException('Publikasi RDF ke Fuseki gagal dengan HTTP '.$response->status().'.');
        }

        $verification = $this->verifyGraph($graphUri);
        if (!$verification['verified']) {
            throw new RuntimeException('Graph telah dikirim, tetapi triple belum dapat diverifikasi melalui SPARQL.');
        }

        return [
            'published' => true,
            'verified' => true,
            'triple_count' => $verification['triple_count'],
        ];
    }

    public function verifyGraph(string $graphUri): array
    {
        $query = 'SELECT (COUNT(*) AS ?tripleCount) WHERE { GRAPH <'.$graphUri.'> { ?s ?p ?o } }';
        $result = $this->query($query);
        $count = (int) ($result['results']['bindings'][0]['tripleCount']['value'] ?? 0);

        return ['verified' => $count > 0, 'triple_count' => $count];
    }

    private function request(): PendingRequest
    {
        $request = Http::timeout((int) config('semantic.fuseki.timeout', 10))
            ->accept('*/*');
        $username = (string) config('semantic.fuseki.username', '');
        $password = (string) config('semantic.fuseki.password', '');

        if ($username !== '') {
            $request = $request->withBasicAuth($username, $password);
        }

        return $request;
    }

    private function requireConfigured(): void
    {
        if (!$this->isConfigured()) {
            throw new RuntimeException('Fuseki belum dikonfigurasi. Aktifkan FUSEKI_ENABLED dan isi endpoint query/update/data.');
        }
    }
}
